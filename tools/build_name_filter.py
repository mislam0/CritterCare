#!/usr/bin/env python3
"""Compile vendored, licensed lists and Unicode folds for offline GDScript use.
No network requests. Re-run after editing data/moderation/policy.json.
"""
from pathlib import Path
import hashlib
import json
import re
import unicodedata as ud

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'data/moderation'
SOURCE = BASE / 'source'


def build():
    policy = json.loads((BASE / 'policy.json').read_text())
    confusables = {}
    for line in (SOURCE / 'confusables.txt').read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        src, target, *_ = [part.strip() for part in line.split(';')]
        codes = src.split()
        if len(codes) == 1:
            confusables[int(codes[0], 16)] = ''.join(chr(int(c, 16)) for c in target.split())

    def basic(value):
        return ''.join(c for c in ud.normalize('NFKD', value.casefold()) if not ud.category(c).startswith('M'))

    def fold_char(char):
        value = basic(char)
        # Keep ASCII letters stable. Map non-ASCII look-alikes, including
        # mathematical/full-width letters, without claiming full UTS39 compliance.
        for _ in range(3):
            result = ''.join(confusables.get(ord(c), c) if ord(c) > 127 else c for c in value)
            result = basic(result)
            if result == value:
                break
            value = result
        return value

    mapping = {}
    for cp in range(0x110000):
        char = chr(cp)
        value = fold_char(char)
        if value != char:
            mapping[str(cp)] = value

    def fold(value):
        return ''.join(fold_char(c) for c in value)

    def key(value):
        return ''.join(c for c in fold(value) if c.isalnum())

    def collapse(value):
        return re.sub(r'(.)\1+', r'\1', value)

    words = set()
    files = []
    for path in sorted((SOURCE / 'ldnoobw').iterdir()):
        if path.is_file() and path.name[0].islower() and '.' not in path.name:
            files.append(path)
    files.append(SOURCE / 'better_profanity/words.txt')
    excluded = {key(x) for x in policy['neutral_terms']}
    for path in files:
        for word in path.read_text().splitlines():
            normalized = key(word.strip())
            if 2 <= len(normalized) <= 64 and normalized not in excluded:
                words.add(normalized)
    words.update(key(x) for x in policy['additional_terms'])
    strong = {key(x) for x in policy['strong_roots']}
    token_only = {key(x) for x in policy['token_only']}
    inner = {x for x in words if len(x) >= 5 and x not in token_only} | strong
    # Preserve short exact words. Only longer inner roots get repeat folding.
    inner_folded = {collapse(x) for x in inner if len(collapse(x)) >= 4}
    allowed = {key(x) for x in policy['friendly_names']}
    result = {
        'FOLD': mapping,
        'WORDS': sorted(words),
        'WORD_REPEATS': sorted({collapse(x) for x in words if len(collapse(x)) >= 2}),
        'INNER': sorted(inner),
        'REPEATED': sorted(inner_folded),
        'FUZZY': sorted(x for x in strong if len(x) >= 4 and x not in token_only),
        'FRIENDLY': sorted(allowed),
    }
    output = ['extends RefCounted', '## Generated by tools/build_name_filter.py; see third_party/name_filter/NOTICE.md.']
    for name, value in result.items():
        output.append('const ' + name + ' = ' + json.dumps(value, ensure_ascii=False, separators=(',', ':')))
    (BASE / 'lexicon.gd').write_text('\n'.join(output) + '\n')
    manifest = {
        'word_entries': len(words), 'language_lists': len(files) - 1,
        'inner_entries': len(inner), 'unicode_folds': len(mapping),
        'python_unicode_version': ud.unidata_version,
        'inputs': {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in files + [SOURCE/'confusables.txt', BASE/'policy.json']},
    }
    (BASE / 'build_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(f"Compiled {len(words)} terms from {len(files)-1} language lists and the English supplement; {len(mapping)} Unicode folds.")


if __name__ == '__main__':
    build()
